const dictionaries: Record<Lang, Record<TextKey, string>> = { de, en };
const listeners = new Set<() => void>();

function initial(): Lang {
  const saved = localStorage.getItem("phreox.site.lang");

  return saved === "de" || saved === "en" ? saved : navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

let current: Lang = initial();

export function setLang(lang: Lang) {
  current = lang;
  localStorage.setItem("phreox.site.lang", lang);
  document.documentElement.lang = lang;
  listeners.forEach((listener) => listener());
}

document.documentElement.lang = current;

/** The text function and the language; the components redraw when the language changes. */
export function useT() {
  const lang = useSyncExternalStore((listener) => {
    listeners.add(listener);

    return () => listeners.delete(listener);
  }, () => current);

  return { lang, t: (key: TextKey) => dictionaries[lang][key] };
}
